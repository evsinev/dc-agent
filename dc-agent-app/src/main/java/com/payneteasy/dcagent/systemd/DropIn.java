package com.payneteasy.dcagent.systemd;

import com.payneteasy.dcagent.systemd.SandboxPlan.Kind;
import com.payneteasy.dcagent.systemd.SandboxPlan.Rule;

import java.nio.file.Path;
import java.util.List;
import java.util.Map;

/**
 * The drop-in {@code /etc/systemd/system/dc-agent.service.d/paths.conf}: the launcher line with every rule
 * of the plan, ReadWritePaths= / NoExecPaths= for the paths the agent writes, the environment the plan was
 * made for. The first line (version) is the only one {@code --check} ignores.
 */
final class DropIn {

    static final Path INSTALLED = Path.of("/etc/systemd/system/dc-agent.service.d/paths.conf");

    private DropIn() {
    }

    static String render(SandboxPlan aPlan, UnitSettings aSettings, Path aConfigDir, Path aAgentHome, String aVersion) {
        StringBuilder out = new StringBuilder();
        out.append("# Generated by dc-agent systemd-unit ").append(aVersion).append(" — regenerate after any config change, do not edit\n");
        out.append(aSettings.optionsLine()).append('\n');
        out.append("# from ").append(aConfigDir).append("; every launcher rule and what it is for:\n");
        for (Rule rule : aPlan.rules()) {
            out.append("#   ").append(rule.kind().option()).append(' ').append(rule.path())
                    .append("  — ").append(rule.source()).append(": ").append(rule.why()).append('\n');
        }
        for (Map.Entry<Integer, String> port : aPlan.ports.entrySet()) {
            out.append("#   --connect-tcp ").append(port.getKey()).append("  — ").append(port.getValue()).append('\n');
        }

        out.append("[Service]\n");
        if (aSettings.slice() != null) {
            out.append("Slice=").append(aSettings.slice()).append('\n');
        }
        for (Map.Entry<String, String> variable : aSettings.environment().entrySet()) {
            out.append("Environment=").append(variable.getKey()).append('=').append(variable.getValue()).append('\n');
        }
        if (aPlan.protectHome) {
            out.append("# a path the agent uses lies under /home, /root or /run/user\n");
            out.append("ProtectHome=read-only\n");
        }

        Path launcher = aAgentHome.resolve("dc-agent-landlock");
        Path agent    = aAgentHome.resolve("dc-agent");
        out.append("ExecStart=\n");
        out.append("ExecStart=").append(launcher).append(" --min-abi 6 --listen-tcp ").append(aSettings.listen()).append(" \\\n");
        for (Rule rule : aPlan.rules()) {
            out.append("  ").append(rule.kind().option()).append(' ').append(rule.path()).append(" \\\n");
        }
        for (Integer port : aPlan.ports.keySet()) {
            out.append("  --connect-tcp ").append(port).append(" \\\n");
        }
        out.append("  -- ").append(agent).append('\n');

        List<Path> written = written(aPlan);
        Path       ldDir   = aPlan.rules(Kind.RX).stream().map(Rule::path).filter(p -> !p.equals(agent)).map(Path::getParent)
                .findFirst().orElse(Path.of("/usr/lib64"));
        out.append("ExecPaths=").append(launcher).append(' ').append(agent).append(' ').append(ldDir).append('\n');
        for (Path path : written) {
            out.append("ReadWritePaths=").append(path).append('\n');
        }
        out.append("NoExecPaths=/tmp /var/tmp\n");
        for (Path path : written) {
            out.append("NoExecPaths=").append(path).append('\n');
        }
        return out.toString();
    }

    /**
     * The paths written besides the unit's own (/dev/null: PrivateDevices; /tmp: PrivateTmp) and the
     * supervise fifos (writing a fifo needs no writable mount).
     */
    static List<Path> written(SandboxPlan aPlan) {
        List<Path> supervise = aPlan.services.stream().map(SandboxPlan.Service::supervise).toList();
        return aPlan.rules(Kind.RW).stream().map(Rule::path)
                .filter(path -> !path.equals(Path.of("/dev/null")) && !path.equals(Path.of("/tmp"))) // NOSONAR java:S5443 compared, not used
                .filter(path -> !supervise.contains(path.getParent()))
                .toList();
    }

    /** The drop-in without its first line (the version), for {@code --check}. */
    static String body(String aDropIn) {
        int newline = aDropIn.indexOf('\n');
        return newline < 0 ? "" : aDropIn.substring(newline + 1);
    }
}
